import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { checkDesignSystemDeadExports } from "./check-design-system-dead-exports.mjs";
import { normalizeRelative, repoRoot } from "./lib/repo.mjs";

const componentIndexRelativePath = "packages/design-system/COMPONENT_INDEX.md";
const generatedBy = "pnpm run generate:design-system-component-index";

function escapeMarkdownTableCell(value) {
  return String(value).replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function humanizeSymbolName(symbol) {
  const words = symbol
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .trim();

  return words.length > 0 ? words : symbol;
}

function purposeForRecord(record) {
  if (record.purpose) {
    return record.purpose;
  }

  const humanizedName = humanizeSymbolName(record.symbol);
  if (humanizedName.toLowerCase() === record.symbol.toLowerCase() && record.symbol.length <= 3) {
    return `Purpose not documented; symbol name only: ${record.symbol}.`;
  }

  return `Purpose not documented; symbol name suggests: ${humanizedName}.`;
}

function exampleConsumerForSymbol(consumersBySymbol, symbol) {
  const consumers = consumersBySymbol[symbol] ?? [];
  return consumers[0] ?? "No production consumer yet.";
}

function buildIndexRows(result) {
  return result.publicSurface.map((record) => ({
    symbol: record.symbol,
    module: record.sourceRelativePath,
    purpose: purposeForRecord(record),
    exampleConsumer: exampleConsumerForSymbol(result.consumersBySymbol, record.symbol),
  }));
}

export async function buildDesignSystemComponentIndex(options = {}) {
  const result = await checkDesignSystemDeadExports(options);
  const rows = buildIndexRows(result);

  const tableRows = rows.map(
    (row) =>
      `| \`${escapeMarkdownTableCell(row.symbol)}\` | \`${escapeMarkdownTableCell(row.module)}\` | ${escapeMarkdownTableCell(row.purpose)} | \`${escapeMarkdownTableCell(row.exampleConsumer)}\` |`,
  );

  const modulesCovered = new Set(rows.map((row) => row.module)).size;

  return {
    content: `# Design System Component Index

<!-- Generated by ${generatedBy}. Do not edit by hand. -->

This index is generated from the root \`@chase-sets/design-system\` export surface and the production consumer inventory used by \`scripts/check-design-system-dead-exports.mjs\`.

- Runtime exports indexed: ${rows.length}
- Source modules covered: ${modulesCovered}
- Example consumers scan: production files under \`bounded-contexts/\` and \`deployables/\`, excluding tests

| Component/export | Module | One-line purpose | Example consumer file |
| --- | --- | --- | --- |
${tableRows.join("\n")}
`,
    rows,
    modulesCovered,
  };
}

function checkExpectedFile(filePath, expectedContent, rootDir) {
  if (!existsSync(filePath)) {
    throw new Error(`${normalizeRelative(filePath, rootDir)} is missing`);
  }

  const currentContent = readFileSync(filePath, "utf8");
  if (currentContent !== expectedContent) {
    throw new Error(`${normalizeRelative(filePath, rootDir)} is stale`);
  }
}

export async function syncDesignSystemComponentIndex(options = {}) {
  const rootDir = path.resolve(options.repoRoot ?? repoRoot);
  const outputPath = path.join(rootDir, componentIndexRelativePath);
  const { content, rows, modulesCovered } = await buildDesignSystemComponentIndex({ ...options, repoRoot: rootDir });

  if (options.check) {
    checkExpectedFile(outputPath, content, rootDir);
    return { checked: true, rows, modulesCovered };
  }

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, content, "utf8");
  return { checked: false, rows, modulesCovered };
}

function parseArgs(args) {
  if (args.length === 0) {
    return { check: false };
  }

  if (args.length === 1 && args[0] === "--check") {
    return { check: true };
  }

  throw new Error("Usage: node ./scripts/generate-design-system-component-index.mjs [--check]");
}

async function main() {
  const result = await syncDesignSystemComponentIndex(parseArgs(process.argv.slice(2)));
  console.log(
    result.checked
      ? `Design-system component index is current (${result.rows.length} exports across ${result.modulesCovered} modules).`
      : `Design-system component index generated (${result.rows.length} exports across ${result.modulesCovered} modules).`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
