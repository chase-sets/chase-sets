function storedZip(entries) {
  const localParts = [];
  const centralParts = [];
  let offset = 0;
  for (const [name, bytes] of entries) {
    const nameBytes = Buffer.from(name);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt32LE(bytes.length, 18);
    local.writeUInt32LE(bytes.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    localParts.push(local, nameBytes, bytes);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt32LE(bytes.length, 20);
    central.writeUInt32LE(bytes.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt32LE(offset, 42);
    centralParts.push(central, nameBytes);
    offset += local.length + nameBytes.length + bytes.length;
  }
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(Buffer.concat(centralParts).length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...localParts, ...centralParts, end]);
}

function issueAuthority() {
  const issues = new Map(
    LEGACY.map(([number, node_id, title]) => [
      number,
      { number, node_id, title, body: LEGACY_BODY, state: "open", state_reason: null },
    ]),
  );
  const calls = [];
  const readCounts = new Map();
  const state = {
    issues,
    calls,
    failPatchNumber: null,
    ambiguousPatchNumber: null,
    driftOnSecondReadNumber: null,
    fetchImpl: async (input, request = {}) => {
      const url = new URL(input);
      const method = request.method ?? "GET";
      const match = url.pathname.match(/\/issues\/(\d+)$/);
      const number = match ? Number(match[1]) : null;
      calls.push({ method, number, path: url.pathname });
      if (!match || !issues.has(number)) return jsonResponse({}, { status: 404 });
      if (method === "GET") {
        const readCount = (readCounts.get(number) ?? 0) + 1;
        readCounts.set(number, readCount);
        if (state.driftOnSecondReadNumber === number && readCount === 2) {
          issues.set(number, { ...issues.get(number), body: `${issues.get(number).body}\nexternal concurrent edit` });
        }
        return jsonResponse(issues.get(number));
      }
      if (method !== "PATCH") return jsonResponse({}, { status: 405 });
      if (state.failPatchNumber === number) return jsonResponse({}, { status: 503 });
      const desired = JSON.parse(request.body);
      const saved = { ...issues.get(number), ...desired };
      if (desired.state === "open" && desired.state_reason === undefined) saved.state_reason = null;
      issues.set(number, saved);
      if (state.ambiguousPatchNumber === number) {
        state.ambiguousPatchNumber = null;
        throw new Error("connection reset after write");
      }
      return jsonResponse(saved);
    },
  };
  return state;
}

function markerCount(body, version) {
  return String(body).split(`<!-- ${version} `).length - 1;
}
