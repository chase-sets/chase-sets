function pagedRuns(url, runs) {
  const page = Number(url.searchParams.get("page") ?? 1);
  const start = (page - 1) * 100;
  const values = runs.slice(start, start + 100);
  const link = start + values.length < runs.length ? nextLink(url, page + 1) : null;
  return jsonResponse({ total_count: runs.length, workflow_runs: values }, { link });
}

function nextLink(url, page) {
  const next = new URL(url);
  next.searchParams.set("page", String(page));
  return `<${next}>; rel="next"`;
}

function jsonResponse(payload, options = {}) {
  const status = options.status ?? 200;
  return {
    ok: status >= 200 && status < 300,
    status,
    headers: {
      get: (name) => {
        if (String(name).toLowerCase() === "link") return options.link ?? null;
        if (String(name).toLowerCase() === "x-ratelimit-remaining") return options.rateRemaining ?? null;
        if (String(name).toLowerCase() === "etag") return options.etag ?? null;
        return null;
      },
    },
    json: async () => structuredClone(payload),
  };
}

