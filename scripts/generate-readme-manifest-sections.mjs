import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { listContextManifests, listWorkspacePackages, normalizeRelative, repoRoot } from "./lib/repo.mjs";

const readmeRelativePath = "README.md";
const generatedBy = "pnpm run generate:readme-manifest-sections";

function formatInlineCodeList(values) {
  return values.map((value) => `\`${value}\``).join(", ");
}

function sentenceFromList(values, emptyFallback) {
  if (!Array.isArray(values) || values.length === 0) {
    return emptyFallback;
  }

  return formatInlineCodeList(values);
}

export function buildBoundedContextsSection(options = {}) {
  const contexts = listContextManifests(options);
  const rows = contexts.map(({ dirName, manifest }) => {
    const contextName = manifest.contextName ?? dirName;
    const packageName = manifest.packageName ?? "package name not declared";
    const ownedNouns = sentenceFromList(manifest.ownedNouns, "no owned nouns declared");
    return `- \`${contextName}\` ([README](bounded-contexts/${dirName}/README.md), \`${packageName}\`): owned nouns ${ownedNouns}.`;
  });

  return `## Bounded Contexts

<!-- Generated by ${generatedBy}. Do not edit by hand. -->

Each context has its own \`README.md\` and \`GLOSSARY.md\` where useful. Treat those files as the local source of truth before editing behavior. The list below is generated from \`bounded-contexts/*/context.json\`; directories without a manifest are not implemented contexts.

${rows.join("\n")}

`;
}

function deployableScriptSummary(packageJson) {
  const scriptNames = Object.keys(packageJson.scripts ?? {}).sort((left, right) => left.localeCompare(right, "en"));
  return sentenceFromList(scriptNames, "no package scripts declared");
}

export function buildDeployablesSection(options = {}) {
  const rootDir = options.repoRoot ?? repoRoot;
  const deployables = listWorkspacePackages({ repoRoot: rootDir, roots: ["deployables"] }).sort((left, right) =>
    left.dirName.localeCompare(right.dirName, "en"),
  );
  const rows = deployables.map(
    ({ dirName, name, packageJson }) =>
      `- \`deployables/${dirName}\` (\`${name}\`): package scripts ${deployableScriptSummary(packageJson)}.`,
  );

  return `## Deployables

<!-- Generated by ${generatedBy}. Do not edit by hand. -->

Deployables are thin composition roots. Business behavior should not live in deployables. Every package-backed directory under \`deployables/\` is listed, including operational services and test harnesses; omissions are intentional only for directories without \`package.json\`.

${rows.join("\n")}

Default local ports are sandbox-aware. Each worktree receives a stable
port block derived from its path so multiple worktrees can run at the same
time. Use \`pnpm run sandbox:doctor\` to print the current worktree's URLs.
The fallback ports below are still used when running deployables directly
without the sandbox env:

| Surface | URL |
| --- | --- |
| Dev portal | <http://localhost:6170> |
| Admin web | <http://localhost:6172> |
| Marketplace web | <http://localhost:6173> |
| Platform API | <http://localhost:6182> |
| Platform worker | <http://localhost:6183> |

`;
}

function replaceSection(content, heading, nextHeading, replacement) {
  const start = content.indexOf(`${heading}\n`);
  if (start === -1) {
    throw new Error(`${heading} section is missing`);
  }

  const end = content.indexOf(`\n${nextHeading}\n`, start);
  if (end === -1) {
    throw new Error(`${nextHeading} section after ${heading} is missing`);
  }

  return `${content.slice(0, start)}${replacement}${content.slice(end + 1)}`;
}

export function buildReadmeWithGeneratedSections(options = {}) {
  const rootDir = path.resolve(options.repoRoot ?? repoRoot);
  const readmePath = path.join(rootDir, readmeRelativePath);
  const currentContent = readFileSync(readmePath, "utf8");
  const withContexts = replaceSection(
    currentContent,
    "## Bounded Contexts",
    "## Deployables",
    buildBoundedContextsSection({ repoRoot: rootDir }),
  );
  return replaceSection(
    withContexts,
    "## Deployables",
    "## Prerequisites",
    buildDeployablesSection({ repoRoot: rootDir }),
  );
}

function checkExpectedFile(filePath, expectedContent, rootDir) {
  if (!existsSync(filePath)) {
    throw new Error(`${normalizeRelative(filePath, rootDir)} is missing`);
  }

  const currentContent = readFileSync(filePath, "utf8");
  if (currentContent !== expectedContent) {
    throw new Error(`${normalizeRelative(filePath, rootDir)} has stale generated manifest sections`);
  }
}

export function syncReadmeManifestSections(options = {}) {
  const rootDir = path.resolve(options.repoRoot ?? repoRoot);
  const outputPath = path.join(rootDir, readmeRelativePath);
  const content = buildReadmeWithGeneratedSections({ repoRoot: rootDir });

  if (options.check) {
    checkExpectedFile(outputPath, content, rootDir);
    return { checked: true };
  }

  writeFileSync(outputPath, content, "utf8");
  return { checked: false };
}

function parseArgs(args) {
  if (args.length === 0) {
    return { check: false };
  }

  if (args.length === 1 && args[0] === "--check") {
    return { check: true };
  }

  throw new Error("Usage: node ./scripts/generate-readme-manifest-sections.mjs [--check]");
}

function main() {
  const result = syncReadmeManifestSections(parseArgs(process.argv.slice(2)));
  console.log(result.checked ? "README manifest sections are current." : "README manifest sections generated.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
