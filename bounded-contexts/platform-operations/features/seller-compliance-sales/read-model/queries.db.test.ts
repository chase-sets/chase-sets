    expect(afterAll!.occurred_at).toEqual(new Date(CAPTURED_AT));

    // A stale group version updates nothing.
    const before = await readSales();
    await deliver(paymentCaptured(1, { capturedAt: "2020-01-01T00:00:00.000Z" }), orderCreated(ORDER_ONE, 1));
    expect(await readSales()).toEqual(before);

    // A cancellation does not block or rewrite creation fields.
    await deliver(orderCancelled(ORDER_ONE, 2));
