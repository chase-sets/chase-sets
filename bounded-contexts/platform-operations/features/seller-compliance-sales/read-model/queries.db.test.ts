    expect(orderFirst[0]!.occurred_at).toEqual(new Date(CAPTURED_AT));
    expect(orderFirst[0]!.cancelled_at).toEqual(new Date(CANCELLED_AT));
    expect(orderFirst[0]!.recorded_at).toEqual(new Date(RECORDED_AT));
