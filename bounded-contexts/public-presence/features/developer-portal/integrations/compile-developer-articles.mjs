import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { flattenMcpTools } from "../../../../../infrastructure/platform-runtime/mcp-contracts.ts";
import { compileHelpArticleCorpus } from "../../help/integrations/compile-help-articles.mjs";
import { assertPublicCopyGuard } from "../../help/domain/public-copy-guard.mjs";

const integrationsDirectory = dirname(fileURLToPath(import.meta.url));
const developerPortalDirectory = resolve(integrationsDirectory, "..");
const articlesDirectory = join(developerPortalDirectory, "domain", "articles");
const generatedDirectory = join(developerPortalDirectory, "domain", "generated");
const generatedArticlesFile = join(generatedDirectory, "articles.ts");
const generatedToolCatalogFile = join(generatedDirectory, "mcp-tool-catalog.ts");

export async function compileDeveloperArticleCorpus(sources) {
  const articles = compileHelpArticleCorpus(sources, {
    defaultPath: ({ slug }) => `/developers/${slug}`,
    expectedAudience: "developer",
    includeCategoryPaths: false,
    rootPath: "/developers",
  });
  const copy = JSON.stringify(articles);
  assertPublicCopyGuard({ corpus: "developer", copy, guard: "launch-language" });
  assertPublicCopyGuard({ corpus: "developer", copy, guard: "agent-commerce" });
  return articles;
}

export function compileMcpToolCatalog() {
  return flattenMcpTools()
    .map((tool) => ({
      name: tool.name,
      title: tool.title,
      description: tool.description,
      availability: tool.availability ?? "planned",
      serviceId: tool.serviceId,
      risk: tool.risk,
      inputSchema: tool.inputSchema,
      ...(tool.outputSchema ? { outputSchema: tool.outputSchema } : {}),
      permissionBoundary: tool.permissionBoundary,
      guardrails: tool.guardrails,
      expectedUsage: tool.expectedUsage,
    }))
    .sort((left, right) => left.availability.localeCompare(right.availability) || left.name.localeCompare(right.name));
}

async function renderDeveloperArticles(articles) {
  return format(
    `// Generated by features/developer-portal/integrations/compile-developer-articles.mjs. Do not edit by hand.\n\nimport type { DeveloperArticle } from "../developer-article-model";\n\nexport const developerArticles = ${JSON.stringify(articles, null, 2)} as const satisfies readonly DeveloperArticle[];\n`,
    { parser: "typescript", printWidth: 120 },
  );
}

async function renderMcpToolCatalog(tools) {
  return format(
    `// Generated by features/developer-portal/integrations/compile-developer-articles.mjs from infrastructure/platform-runtime/mcp-contracts.ts. Do not edit by hand.\n\nimport type { DeveloperMcpToolCatalogEntry } from "../developer-article-model";\n\nexport const mcpToolCatalog = ${JSON.stringify(tools, null, 2)} as const satisfies readonly DeveloperMcpToolCatalogEntry[];\n`,
    { parser: "typescript", printWidth: 120 },
  );
}

export async function compileRepositoryDeveloperCorpus() {
  const fileNames = (await readdir(articlesDirectory)).filter((fileName) => fileName.endsWith(".md")).sort();
  const sources = await Promise.all(
    fileNames.map(async (fileName) => ({
      fileName,
      source: await readFile(join(articlesDirectory, fileName), "utf8"),
    })),
  );
  return compileDeveloperArticleCorpus(sources);
}

async function main() {
  const articles = await compileRepositoryDeveloperCorpus();
  const tools = compileMcpToolCatalog();
  const outputs = [
    { file: generatedArticlesFile, content: await renderDeveloperArticles(articles) },
    { file: generatedToolCatalogFile, content: await renderMcpToolCatalog(tools) },
  ];
  if (process.argv.includes("--check")) {
    for (const output of outputs) {
      const current = await readFile(output.file, "utf8").catch(() => "");
      if (current !== output.content) {
        throw new Error(
          `${relative(process.cwd(), output.file)} is stale; run pnpm --filter @chase-sets/public-presence run compile:developer-articles`,
        );
      }
    }
    return;
  }
  await mkdir(generatedDirectory, { recursive: true });
  for (const output of outputs) await writeFile(output.file, output.content, "utf8");
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) await main();
