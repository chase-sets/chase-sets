import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { registerHooks } from "node:module";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

// The registry's domain modules use the repo-standard extensionless relative
// imports, which raw `node --experimental-strip-types` cannot resolve on its
// own. Retry failed relative specifiers with a `.ts` extension so this
// compiler loads the canonical domain registry directly instead of keeping a
// lookalike copy of it.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if ((specifier.startsWith("./") || specifier.startsWith("../")) && !/\.[a-z]+$/i.test(specifier)) {
        return nextResolve(`${specifier}.ts`, context);
      }
      throw error;
    }
  },
});

const { isConsentActivatable, validatePublicPolicyArtifactStructure } = await import("../domain/policy-artifact.ts");
const { publicPolicyRegistry } = await import("../domain/policy-registry.ts");
const { evaluateCanonicalClaimConsistency } = await import("../domain/canonical-claim-guard.ts");

const integrationsDirectory = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(integrationsDirectory, "../../../../..");
const generatedContractDirectory = resolve(repoRoot, "contracts", "public-docs", "generated");

const generatedBy = "bounded-contexts/public-presence/features/policies/integrations/compile-policy-publications.mjs";
const compileCommand = "pnpm --filter @chase-sets/public-presence run compile:public-policies";

function pascalCase(policyKey) {
  return policyKey
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function recordExportName(policyKey) {
  return `public${pascalCase(policyKey)}PublicationRecord`;
}

function moduleFileName(policyKey) {
  return `${policyKey}-publication.ts`;
}

function assertValidCorpus(registry) {
  const errors = registry.flatMap((entry) => validatePublicPolicyArtifactStructure(entry.artifact));
  const seenKeys = new Set();
  for (const entry of registry) {
    const key = entry.artifact.metadata.policyKey;
    if (seenKeys.has(key)) {
      errors.push(`Public policy corpus registers policy key '${key}' more than once.`);
    }
    seenKeys.add(key);
  }
  for (const violation of evaluateCanonicalClaimConsistency(registry, repoRoot)) {
    errors.push(
      `${violation.policyKey} section '${violation.sectionId}' canonical claim '${violation.claimId}' ${violation.reason}`,
    );
  }
  if (errors.length > 0) {
    throw new Error(`Public policy corpus failed closed-schema validation:\n${errors.join("\n")}`);
  }
}

function fingerprintArtifactContent(artifact) {
  const ownedContent = {
    title: artifact.title,
    description: artifact.description,
    sections: artifact.sections.map((section) => ({
      id: section.id,
      title: section.title,
      draftText: section.draftText,
      reviewStatus: section.reviewStatus,
      claimDisclosures: section.claimDisclosures ?? [],
      reviewManifest: {
        scopeNote: section.reviewManifest.scopeNote,
        decisionRefs: section.reviewManifest.decisionRefs,
        productTruthRefs: section.reviewManifest.productTruthRefs,
        openQuestions: section.reviewManifest.openQuestions,
        assumptions: section.reviewManifest.assumptions.map((assumption) => ({
          assertion: assumption.assertion,
          evidenceRef: assumption.evidenceRef,
        })),
      },
    })),
  };
  return `sha256:${createHash("sha256").update(JSON.stringify(ownedContent)).digest("hex")}`;
}

async function renderPublicationModule(entry) {
  const { artifact, requiredSubjectIds } = entry;
  const { launchRequired: _launchRequired, ...legacyOrder } = artifact.metadata;
  const record = {
    ...artifact.metadata,
    contentFingerprint: fingerprintArtifactContent(artifact),
    consentActivatable: isConsentActivatable(artifact, requiredSubjectIds),
  };
  const policyKey = artifact.metadata.policyKey;
  const legacyExport =
    policyKey === "terms-of-service"
      ? `\nexport const publicTermsOfServicePublicationMetadata = ${JSON.stringify(legacyOrder, null, 2)} as const satisfies PublicTermsOfServicePublicationMetadata;\n`
      : "";
  const legacyImport = policyKey === "terms-of-service" ? ", PublicTermsOfServicePublicationMetadata" : "";

  return format(
    `// Generated by ${generatedBy}. Do not edit by hand.\n\nimport type { PublicPolicyPublicationRecord${legacyImport} } from "../policy-corpus";\n\nexport const ${recordExportName(policyKey)} = ${JSON.stringify(record, null, 2)} as const satisfies PublicPolicyPublicationRecord<"${policyKey}">;\n${legacyExport}`,
    { parser: "typescript", printWidth: 120 },
  );
}

async function renderCorpusIndex(registry) {
  const sortedKeys = registry.map((entry) => entry.artifact.metadata.policyKey).toSorted();
  const imports = sortedKeys
    .map((key) => `import { ${recordExportName(key)} } from "./${key}-publication";`)
    .join("\n");
  const aggregateEntries = sortedKeys.map((key) => `  "${key}": ${recordExportName(key)},`).join("\n");
  const reExports = sortedKeys.map((key) => `export { ${recordExportName(key)} };`).join("\n");

  return format(
    `// Generated by ${generatedBy}. Do not edit by hand.\n// Content-insensitive corpus index: stable imports and re-exports keyed by the\n// registry's policy keys only, so editing one document's content changes only\n// that document's generated module and never this file.\n\nimport type { PublicPolicyKey, PublicPolicyPublicationRecord } from "../policy-corpus";\n${imports}\n\nexport const publicPolicyPublicationRecords = {\n${aggregateEntries}\n} as const satisfies Readonly<Record<PublicPolicyKey, PublicPolicyPublicationRecord>>;\n\n${reExports}\n`,
    { parser: "typescript", printWidth: 120 },
  );
}

export async function renderPublicPolicyPublicationContracts(registry = publicPolicyRegistry) {
  assertValidCorpus(registry);
  const modules = [];
  for (const entry of registry) {
    modules.push({
      relativePath: moduleFileName(entry.artifact.metadata.policyKey),
      content: await renderPublicationModule(entry),
    });
  }
  modules.push({ relativePath: "index.ts", content: await renderCorpusIndex(registry) });
  return modules;
}

async function discoverGeneratedModules() {
  const entries = await readdir(generatedContractDirectory).catch(() => []);
  return entries.filter((entry) => entry === "index.ts" || entry.endsWith("-publication.ts")).toSorted();
}

async function main() {
  const rendered = await renderPublicPolicyPublicationContracts();
  const expected = rendered.map((module) => module.relativePath).toSorted();

  if (process.argv.includes("--check")) {
    const discovered = await discoverGeneratedModules();
    const orphaned = discovered.filter((name) => !expected.includes(name));
    const stale = [];
    for (const module of rendered) {
      const target = resolve(generatedContractDirectory, module.relativePath);
      const current = await readFile(target, "utf8").catch(() => "");
      if (current !== module.content) {
        stale.push(relative(process.cwd(), target));
      }
    }
    if (orphaned.length > 0 || stale.length > 0) {
      const details = [
        ...orphaned.map((name) => `orphaned generated module not owned by the registry: ${name}`),
        ...stale.map((name) => `stale generated module: ${name}`),
      ];
      throw new Error(
        `public-docs policy corpus check failed (discovered ${discovered.length}, expected ${expected.length} generated modules):\n${details.join("\n")}\nRun ${compileCommand}.`,
      );
    }
    console.log(
      `public-docs policy corpus check: ${expected.length}/${expected.length} generated modules current (${expected.length - 1} documents + index).`,
    );
    return;
  }

  await mkdir(generatedContractDirectory, { recursive: true });
  for (const module of rendered) {
    await writeFile(resolve(generatedContractDirectory, module.relativePath), module.content, "utf8");
  }
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  await main();
}
