import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { termsOfServicePolicyArtifact } from "../domain/terms-of-service.ts";

const integrationsDirectory = dirname(fileURLToPath(import.meta.url));
const generatedContractFile = resolve(
  integrationsDirectory,
  "../../../../..",
  "contracts",
  "public-docs",
  "generated",
  "terms-of-service-publication.ts",
);

export async function renderTermsOfServicePublicationContract() {
  return format(
    `// Generated by bounded-contexts/public-presence/features/policies/integrations/compile-terms-of-service-publication.mjs. Do not edit by hand.\n\nimport type { PublicTermsOfServicePublicationMetadata } from "../index";\n\nexport const publicTermsOfServicePublicationMetadata = ${JSON.stringify(termsOfServicePolicyArtifact.metadata, null, 2)} as const satisfies PublicTermsOfServicePublicationMetadata;\n`,
    { parser: "typescript", printWidth: 120 },
  );
}

async function main() {
  const content = await renderTermsOfServicePublicationContract();
  if (process.argv.includes("--check")) {
    const current = await readFile(generatedContractFile, "utf8").catch(() => "");
    if (current !== content) {
      throw new Error(
        `${relative(process.cwd(), generatedContractFile)} is stale; run pnpm --filter @chase-sets/public-presence run compile:terms-of-service`,
      );
    }
    return;
  }

  await mkdir(dirname(generatedContractFile), { recursive: true });
  await writeFile(generatedContractFile, content, "utf8");
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  await main();
}
